create table posts (
    id          bigint generated by default as identity,
    title       varchar(100)                not null,
    description text                        not null,
    start_date  varchar(8),
    end_date    varchar(8),
    view_count  bigint                      not null default 0,
    created_at  timestamp(6) with time zone not null,
    constraint pk_posts primary key (id)
);

create table contents (
    post_id bigint not null,
    content text   not null,
    constraint pk_contents primary key (post_id),
    constraint fk_contents_post foreign key (post_id) references posts (id)
);

create table post_links (
    id      bigint generated by default as identity,
    post_id bigint        not null,
    title   varchar(100)  not null,
    url     varchar(1000) not null,
    constraint pk_post_links primary key (id),
    constraint fk_post_links_post foreign key (post_id) references posts (id)
);

create index idx_post_links_post on post_links (post_id);

create table post_daily_views (
    id          bigint generated by default as identity,
    post_id     bigint not null,
    report_date date   not null,
    view_count  bigint not null,
    constraint pk_post_daily_views primary key (id),
    constraint uk_post_daily_views_post_date unique (post_id, report_date),
    constraint fk_post_daily_views_post foreign key (post_id) references posts (id) on delete cascade
);

create index idx_post_daily_views_date on post_daily_views (report_date);

create table link_cards (
    id          bigint generated by default as identity,
    title       varchar(50)   not null,
    url         varchar(1000) not null,
    description varchar(255)  not null,
    icon        varchar(1000),
    constraint pk_link_cards primary key (id)
);

create table tag_groups (
    id   bigint generated by default as identity,
    name varchar(30) not null,
    constraint pk_tag_groups primary key (id),
    constraint uk_tag_groups_name unique (name)
);

create table tags (
    id           bigint generated by default as identity,
    tag_group_id bigint       not null,
    name         varchar(255) not null,
    bg_color     varchar(10)  not null,
    t_color      varchar(10)  not null,
    constraint pk_tags primary key (id),
    constraint fk_tags_tag_group foreign key (tag_group_id) references tag_groups (id)
);

create index idx_tags_tag_group on tags (tag_group_id);
