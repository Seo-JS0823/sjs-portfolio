create table careers (
    id         bigint generated by default as identity,
    title      varchar(100) not null,
    start_date varchar(8)   not null,
    end_date   varchar(8),
    constraint pk_careers primary key (id)
);

create table career_keywords (
    id        bigint generated by default as identity,
    career_id bigint      not null,
    name      varchar(50) not null,
    constraint pk_career_keywords primary key (id),
    constraint fk_career_keywords_career foreign key (career_id) references careers (id)
);

create index idx_career_keywords_career on career_keywords (career_id);

create table career_contents (
    id        bigint generated by default as identity,
    career_id bigint not null,
    content   text   not null,
    constraint pk_career_contents primary key (id),
    constraint fk_career_contents_career foreign key (career_id) references careers (id)
);

create index idx_career_contents_career on career_contents (career_id);
